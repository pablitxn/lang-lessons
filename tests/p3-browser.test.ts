import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';

test('P3 mocked views handle all-student paging, denial, races, focus and reflow', { skip: process.env.P3_BROWSER !== '1', timeout: 60000 }, async () => {
  const { chromium } = createRequire(import.meta.url)('playwright');
  const port = 5197;
  const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', String(port), '--strictPort'], { stdio: ['ignore', 'pipe', 'pipe'] });
  let log = '';
  server.stdout.on('data', value => { log += String(value); });
  server.stderr.on('data', value => { log += String(value); });
  let browser: any;
  try {
    for (let i = 0; i < 100 && !log.includes('Local:'); i++) { assert.equal(server.exitCode, null, log); await new Promise(resolve => setTimeout(resolve, 50)); }
    assert.match(log, /Local:/);
    browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE_PATH || '/usr/bin/chromium', headless: true, env: { ...process.env, XDG_CONFIG_HOME: '/tmp/p3-browser-config', XDG_CACHE_HOME: '/tmp/p3-browser-cache' } });
    const page = await browser.newPage();
    const errors: string[] = [], external: string[] = [];
    page.on('pageerror', (error: Error) => errors.push(error.message));
    page.on('request', (request: any) => { if (!request.url().startsWith(`http://127.0.0.1:${port}/`)) external.push(request.url()); });
    const open = (query = '') => page.goto(`http://127.0.0.1:${port}/src/features/accounts/__fixtures__/preview.html?${query}`);
    for (const width of [320, 390, 844, 1024]) {
      await page.setViewportSize({ width, height: 640 });
      await open();
      await page.getByRole('button', { name: 'Next students' }).click();
      const student = page.getByRole('button', { name: 'View progress for student-outside-subset' });
      await student.focus(); await page.keyboard.press('Enter');
      await page.getByText('Mock comment for student-outside-subset:', { exact: false }).waitFor();
      assert.equal(await page.getByRole('heading', { name: 'Progress for student-outside-subset' }).evaluate((el: HTMLElement) => el === document.activeElement), true);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      await page.getByRole('button', { name: 'Back to students' }).click();
      await page.waitForFunction(() => document.activeElement?.textContent === 'View progress for student-outside-subset');
    }
    await open('scenario=loading'); await page.getByRole('status').filter({ hasText: 'Loading' }).waitFor();
    await page.getByRole('button', { name: 'View progress for student-first' }).waitFor();
    await open('scenario=empty'); await page.getByText('No students found.').waitFor();
    await open('scenario=error'); await page.getByRole('alert').waitFor();
    assert.equal(await page.getByText('Private transport detail').count(), 0);
    await page.getByRole('button', { name: 'Try again' }).click(); await page.getByRole('button', { name: 'View progress for student-first' }).waitFor();
    await open('scenario=denied'); await page.getByRole('alert').waitFor();
    assert.equal(await page.getByRole('button', { name: /View progress/ }).count(), 0);
    await open('scenario=unbound'); await page.getByRole('alert').waitFor();
    assert.equal(await page.evaluate(() => (window as any).p3Calls.list), 0);
    await open('scenario=late'); await page.getByRole('button', { name: 'View progress for student-first' }).click();
    await page.getByRole('button', { name: 'Back to students' }).click();
    await page.getByRole('button', { name: 'Next students' }).click();
    await page.getByRole('button', { name: 'View progress for student-outside-subset' }).click();
    await page.getByText('Mock comment for student-outside-subset:', { exact: false }).waitFor();
    await page.waitForTimeout(1000);
    assert.equal(await page.getByText('Mock comment for student-first:', { exact: false }).count(), 0);
    await page.getByRole('button', { name: 'Revoke grants' }).click(); await page.getByRole('alert').waitFor();
    assert.equal(await page.getByText('Mock comment', { exact: false }).count(), 0);
    await open('scenario=mismatch'); await page.getByRole('button', { name: 'View progress for student-first' }).click();
    await page.getByText('Comment could not be verified.').waitFor();
    assert.equal(await page.getByText('Mock comment', { exact: false }).count(), 0);
    await open('view=admin&role=administrator'); await page.getByRole('list', { name: 'Users', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: /Create|Disable|Delete/ }).count(), 0);
    await page.getByRole('button', { name: 'Next users' }).click(); await page.getByRole('heading', { name: 'student-outside-subset@example.test', exact: true }).waitFor();
    await open('scenario=login-error'); await page.getByLabel('Email').fill('fixture@example.test'); await page.getByLabel('Password', { exact: true }).fill('fixture-only');
    await page.getByRole('button', { name: 'Show password', exact: true }).click();
    assert.equal(await page.getByLabel('Password', { exact: true }).getAttribute('type'), 'text');
    await page.getByLabel('Password', { exact: true }).press('Enter'); await page.getByRole('alert').waitFor();
    assert.equal(await page.getByLabel('Password', { exact: true }).inputValue(), '');
    assert.equal(await page.getByLabel('Email').inputValue(), 'fixture@example.test');
    assert.equal(await page.getByLabel('Password', { exact: true }).getAttribute('type'), 'password');
    assert.equal(await page.getByRole('alert').evaluate((el: HTMLElement) => el === document.activeElement), true);
    await open('scenario=login'); await page.getByLabel('Email').fill('fixture@example.test'); await page.getByLabel('Password', { exact: true }).fill('fixture-only');
    await page.getByRole('button', { name: 'Sign in', exact: true }).dblclick(); await page.getByRole('heading', { name: 'All students' }).waitFor();
    assert.equal(await page.evaluate(() => (window as any).p3Calls.login), 1);
    assert.equal(await page.getByRole('button', { name: 'Sign out', exact: true }).count(), 0);
    await page.getByRole('button', { name: 'Preferences', exact: true }).click();
    await page.getByRole('dialog', { name: 'Preferences', exact: true }).getByRole('heading', { name: 'Profile', exact: true }).waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('button', { name: 'Preferences', exact: true }).evaluate((el: HTMLElement) => el === document.activeElement), true);
    await page.getByRole('button', { name: 'Preferences', exact: true }).click();
    await page.getByRole('button', { name: 'Sign out', exact: true }).dblclick();
    await page.getByRole('heading', { name: 'Welcome back.', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => (window as any).p3Calls.logout), 1);
    await open('scenario=logout-error');
    await page.getByRole('button', { name: 'Preferences', exact: true }).click();
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await page.getByRole('dialog', { name: 'Preferences', exact: true }).getByRole('alert').filter({ hasText: 'We couldn’t confirm sign-out.' }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Sign out', exact: true }).isEnabled(), true);
    assert.equal(await page.getByText('Private sign-out failure').count(), 0);
    await page.getByRole('button', { name: 'Close preferences', exact: true }).click();
    assert.equal(await page.getByRole('heading', { name: 'All students', exact: true }).isVisible(), true);
    for (const width of [320, 390, 844, 1024]) {
      await page.setViewportSize({ width, height: 640 });
      for (const query of ['scenario=login', 'view=admin&role=administrator&scenario=manage']) {
        await open(query);
        await page.getByRole('heading', { name: query.includes('login') ? 'Welcome back.' : 'People & access', exact: true }).waitFor();
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        if (!query.includes('login')) {
          await page.getByRole('button', { name: 'Preferences', exact: true }).click();
          await page.getByRole('dialog', { name: 'Preferences', exact: true }).waitFor();
          assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
          await page.keyboard.press('Escape');
        }
      }
    }
    await page.setViewportSize({ width: 320, height: 640 });
    await open('view=admin&role=administrator&scenario=manage');
    assert.equal(await page.getByLabel('New user role').inputValue(), 'student');
    assert.equal(await page.getByRole('button', { name: 'Change role for student@example.test', exact: true }).isDisabled(), true);
    assert.equal(await page.getByText('Password not set · setup link needed', { exact: true }).isVisible(), true);
    assert.equal(await page.getByText('You', { exact: true }).isVisible(), true);
    assert.equal(await page.getByText('student-managed', { exact: true }).isVisible(), false);
    await page.getByLabel('Find accounts on this page', { exact: true }).fill('student@example.test');
    assert.equal(await page.getByRole('heading', { name: 'admin@example.test', exact: true }).count(), 0);
    assert.equal(await page.getByRole('heading', { name: 'student@example.test', exact: true }).isVisible(), true);
    await page.getByLabel('Find accounts on this page', { exact: true }).fill('');
    await page.getByRole('button', { name: 'Deactivate student@example.test', exact: true }).click();
    await page.getByRole('dialog').waitFor();
    assert.match(await page.getByRole('dialog').innerText(), /student@example\.test/);
    assert.doesNotMatch(await page.getByRole('dialog').innerText(), /student-managed/);
    assert.equal(await page.getByRole('button', { name: 'Cancel', exact: true }).evaluate((el: HTMLElement) => el === document.activeElement), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(() => (window as any).p3Calls.mutation), 0);
    await page.getByRole('button', { name: 'Deactivate admin@example.test', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm change', exact: true }).click();
    await page.getByText('This change would remove the last active administrator. No change was made.').waitFor();
    await page.getByRole('button', { name: 'Deactivate student@example.test', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm change', exact: true }).dblclick();
    await page.getByRole('button', { name: 'Reactivate student@example.test', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => (window as any).p3Calls.mutation), 2);
    await page.getByRole('button', { name: 'Reactivate student@example.test', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm change', exact: true }).click();
    await page.getByRole('button', { name: 'Deactivate student@example.test', exact: true }).waitFor();
    await page.getByLabel('Role for student@example.test', { exact: true }).selectOption('professor');
    await page.getByRole('button', { name: 'Change role for student@example.test', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm change', exact: true }).click();
    await page.getByRole('listitem').filter({ has: page.getByRole('heading', { name: 'student@example.test', exact: true }) }).locator('.p3-role-badge').getByText('Teacher', { exact: true }).waitFor();
    await page.getByLabel('New user email').fill('new@example.test');
    await page.getByLabel('New user role').selectOption('student');
    await page.getByRole('button', { name: 'Create account', exact: true }).click();
    await page.getByRole('dialog').waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.getByRole('button', { name: 'Confirm change', exact: true }).click();
    await page.getByRole('heading', { name: 'new@example.test', exact: true }).waitFor();
    await page.getByRole('status').filter({ hasText: 'No email has been sent.' }).waitFor();
    assert.deepEqual(await page.evaluate(() => (window as any).p3Calls.changes.at(-1)), { kind: 'create', email: 'new@example.test', role: 'student' });
    assert.equal(await page.locator('input[type="password"]').count(), 0);
    for (const scenario of ['manage-denied', 'manage-unknown', 'manage-conflict', 'manage-policy']) {
      await open(`view=admin&role=administrator&scenario=${scenario}`);
      await page.getByRole('button', { name: 'Deactivate student@example.test', exact: true }).click();
      await page.getByRole('button', { name: 'Confirm change', exact: true }).click();
      const expected = scenario === 'manage-denied' ? 'Access denied. Your permissions may have changed.' : scenario === 'manage-unknown' ? 'The outcome is unknown.' : scenario === 'manage-conflict' ? 'The account changed.' : 'This action is not available until';
      await page.getByText(expected, { exact: false }).waitFor();
      if (scenario === 'manage-denied') assert.equal(await page.getByRole('list', { name: 'Users', exact: true }).count(), 0);
      if (scenario === 'manage-unknown') assert.equal(await page.getByRole('button', { name: 'Create account', exact: true }).isDisabled(), true);
      assert.equal(await page.evaluate(() => (window as any).p3Calls.mutation), 1);
    }
    await open('scenario=daily');
    await page.getByRole('button', { name: 'View progress for student-first' }).click();
    const firstDay = page.getByRole('region', { name: 'Fixture day one', exact: true });
    await firstDay.getByText('12', { exact: true }).waitFor();
    await firstDay.getByText('Mock morning comment', { exact: true }).waitFor();
    await firstDay.getByText('Mock evening comment', { exact: true }).waitFor();
    assert.equal(await firstDay.getByText('Fixture start 1', { exact: true }).count(), 1);
    assert.equal(await firstDay.getByText('Fixture end 2', { exact: true }).count(), 1);
    await page.getByRole('region', { name: 'Fixture day two', exact: true }).getByText('No session comments found.').waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.getByRole('button', { name: 'Back to students' }).click();
    await page.getByRole('button', { name: 'View progress for student-first' }).click();
    await firstDay.getByText('12', { exact: true }).waitFor();
    await open('scenario=daily-unselected');
    await page.getByRole('button', { name: 'View progress for student-first' }).click();
    await page.getByText('Daily written totals are not available yet.').waitFor();
    assert.deepEqual(errors, []); assert.deepEqual(external, []);
  } finally { await browser?.close(); server.kill('SIGTERM'); }
});
